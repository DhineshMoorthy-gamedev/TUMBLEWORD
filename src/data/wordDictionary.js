/**
 * Fast Mulberry32 32-bit PRNG generator
 * @param {number} seed
 * @returns {() => number}
 */
export function createPRNG(seed = 12345) {
  let s = Math.floor(Number(seed) || 12345) >>> 0;
  return function() {
    s = (s + 0x6D2B79F5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * WordDeck - Stateful shuffle-bag word sampler for endless mode.
 * Guarantees zero duplicate words until the entire tier pool is exhausted.
 */
export class WordDeck {
  constructor(prng) {
    this.prng = typeof prng === 'function' ? prng : createPRNG(Date.now());
    this.usedWords = new Set();
    this.recentHistory = [];
    
    // Seeded shuffle for each length tier (Tiers 1 to 8: lengths 3 to 10)
    this.decks = {
      3: this._createShuffledDeck(WORDS_3),
      4: this._createShuffledDeck(WORDS_4),
      5: this._createShuffledDeck(WORDS_5),
      6: this._createShuffledDeck(WORDS_6),
      7: this._createShuffledDeck(WORDS_7),
      8: this._createShuffledDeck(WORDS_8),
      9: this._createShuffledDeck(WORDS_9),
      10: this._createShuffledDeck(WORDS_10)
    };
    
    this.indices = { 3: 0, 4: 0, 5: 0, 6: 0, 7: 0, 8: 0, 9: 0, 10: 0 };
  }

  _createShuffledDeck(wordList) {
    const deck = [...wordList];
    for (let i = deck.length - 1; i > 0; i--) {
      const j = Math.floor(this.prng() * (i + 1));
      [deck[i], deck[j]] = [deck[j], deck[i]];
    }
    return deck;
  }

  /**
   * Sample the next non-repeating word for a given streak index
   * @param {number} streakIdx
   * @returns {string}
   */
  getNextWord(streakIdx) {
    let tier;
    if (streakIdx < 5) {
      tier = 3;
    } else if (streakIdx < 15) {
      tier = 4;
    } else if (streakIdx < 30) {
      tier = 5;
    } else if (streakIdx < 50) {
      tier = 6;
    } else if (streakIdx < 75) {
      tier = 7;
    } else if (streakIdx < 100) {
      tier = 8;
    } else if (streakIdx < 130) {
      tier = 9;
    } else {
      // Cosmic / Infinity tier: alternating 9 and 10-letter words
      tier = streakIdx % 2 === 0 ? 9 : 10;
    }

    const deck = this.decks[tier];
    let idx = this.indices[tier];

    // If deck exhausted, re-shuffle and reset index
    if (idx >= deck.length) {
      const list = tier === 3 ? WORDS_3 : tier === 4 ? WORDS_4 : tier === 5 ? WORDS_5 : tier === 6 ? WORDS_6 : tier === 7 ? WORDS_7 : tier === 8 ? WORDS_8 : tier === 9 ? WORDS_9 : WORDS_10;
      this.decks[tier] = this._createShuffledDeck(list);
      this.indices[tier] = 0;
      idx = 0;
    }

    let word = this.decks[tier][idx];
    this.indices[tier]++;

    // If recently used, swap with next card in deck to maximize variety
    if (this.recentHistory.includes(word) && this.indices[tier] < this.decks[tier].length) {
      const nextIdx = this.indices[tier];
      const altWord = this.decks[tier][nextIdx];
      this.decks[tier][nextIdx] = word;
      word = altWord;
      this.indices[tier]++;
    }

    this.usedWords.add(word);
    this.recentHistory.push(word);
    if (this.recentHistory.length > 50) {
      this.recentHistory.shift();
    }

    return word;
  }
}

/**
 * Factory to create a WordDeck for a seed
 * @param {number|(() => number)} seedOrPrng
 * @returns {WordDeck}
 */
export function createEndlessWordDeck(seedOrPrng) {
  const prng = typeof seedOrPrng === 'function' ? seedOrPrng : createPRNG(seedOrPrng);
  return new WordDeck(prng);
}

/**
 * Deterministically sample a word for a given streak index (Legacy / standalone helper)
 * @param {(() => number)|WordDeck} prngOrDeck
 * @param {number} streakIdx
 * @returns {string}
 */
export function getSeededWord(prngOrDeck, streakIdx) {
  if (prngOrDeck && typeof prngOrDeck.getNextWord === 'function') {
    return prngOrDeck.getNextWord(streakIdx);
  }

  let pool;
  if (streakIdx < 5) {
    pool = WORDS_3;
  } else if (streakIdx < 15) {
    pool = WORDS_4;
  } else if (streakIdx < 30) {
    pool = WORDS_5;
  } else if (streakIdx < 50) {
    pool = WORDS_6;
  } else if (streakIdx < 75) {
    pool = WORDS_7;
  } else if (streakIdx < 100) {
    pool = WORDS_8;
  } else if (streakIdx < 130) {
    pool = WORDS_9;
  } else {
    pool = streakIdx % 2 === 0 ? WORDS_9 : WORDS_10;
  }

  const prng = typeof prngOrDeck === 'function' ? prngOrDeck : Math.random;
  const idx = Math.floor(prng() * pool.length);
  return pool[idx];
}
